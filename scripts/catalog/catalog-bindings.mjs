/**
 * Read-only frontend and backend bindings generated from the canonical
 * chemistry catalog.
 *
 * One committed artifact (`catalog/chemistry.catalog.json`) is the only source
 * of reagent, ion, reaction, equation, capability, and inverse-candidate data.
 * Both runtimes read it through a generated binding instead of a hand-written
 * copy, so the frontend and the backend cannot drift apart:
 *
 * - Every binding embeds the catalog payload in canonical JSON form plus a
 *   *manifest*: the digest-addressed contract (schema version, catalog version,
 *   locale, catalog/schema digests) and the supported-definition inventory.
 * - Generation is a pure function of the committed catalog and schema, so
 *   regenerating from unchanged artifacts reproduces identical bytes.
 * - Both bindings embed the same manifest, so a divergence in catalog version,
 *   digest, or supported definitions is detectable without executing either
 *   binding (see `check-bindings.mjs`).
 *
 * The embedded data is deeply immutable at runtime: `Object.freeze` in
 * JavaScript, `MappingProxyType`/`tuple` in Python.
 */

import { canonicalizeJson, digestJson } from './canonical-json.mjs';
import { buildDigestRecord } from './catalog-digest.mjs';
import {
  CATALOG_RELATIVE_PATH,
  DIGEST_RELATIVE_PATH,
  JAVASCRIPT_BINDING_RELATIVE_PATH,
  PYTHON_BINDING_RELATIVE_PATH,
  SCHEMA_RELATIVE_PATH,
} from './catalog-paths.mjs';

/**
 * Version of the binding contract itself.
 *
 * It changes when the *shape* of the manifest changes, independently of the
 * catalog release version, so a stale binding generated by an older toolchain
 * is rejected rather than compared field by field against a newer contract.
 */
export const BINDING_CONTRACT_VERSION = '1';

/** Marker names of the embedded literal blocks the parity checker reads. */
export const MANIFEST_BLOCK = 'atomverse:manifest-json';
export const CATALOG_BLOCK = 'atomverse:catalog-json';

/** Number of source characters embedded per generated string-literal line. */
const LITERAL_CHUNK_SIZE = 84;

const sortedCopy = (values) => [...(values ?? [])].sort();

const byField = (field) => (left, right) => {
  if (left[field] === right[field]) return 0;
  return left[field] < right[field] ? -1 : 1;
};

/**
 * Builds the language-independent inventory of definitions a binding claims to
 * support.
 *
 * Only identity and capability facts belong here: the things a frontend and a
 * backend must agree on before either runs a calculation. Presentation detail
 * and localized text stay in the catalog payload. Every list is sorted so the
 * inventory is a pure function of catalog content, not of key insertion order.
 */
export function buildSupportedDefinitions(catalog) {
  const model = catalog?.model ?? {};

  return {
    elements: sortedCopy(catalog?.elements),
    phases: sortedCopy(catalog?.phases),
    speciesIds: sortedCopy(Object.keys(catalog?.species ?? {})),
    ionIds: sortedCopy(Object.keys(catalog?.ions ?? {})),
    reagentIds: sortedCopy(Object.keys(catalog?.reagents ?? {})),
    reactions: Object.entries(catalog?.reactions ?? {})
      .map(([pairKey, reaction]) => ({
        pairKey,
        reactionId: reaction?.id ?? null,
        category: reaction?.category ?? null,
        reactantSet: sortedCopy(reaction?.reactantSet),
        phaseModel: reaction?.phaseModel ?? null,
        pHSupported: Boolean(reaction?.pH),
      }))
      .sort(byField('pairKey')),
    inverseTargets: Object.entries(catalog?.inverseTargets ?? {})
      .map(([id, target]) => ({
        id,
        kind: target?.kind ?? null,
        reactionIds: sortedCopy(target?.reactionIds),
      }))
      .sort(byField('id')),
    categories: sortedCopy(model.categories),
    phaseModels: sortedCopy(Object.keys(model.phaseModels ?? {})),
    inverseGoalKinds: sortedCopy(model.capabilities?.inverse?.supportedGoalKinds),
    pHSupportedReactionIds: sortedCopy(model.capabilities?.pH?.supportedReactionIds),
    bounds: Object.fromEntries(
      Object.keys(model.bounds ?? {})
        .sort()
        .map((name) => [name, model.bounds[name]]),
    ),
    messageLocales: sortedCopy(Object.keys(catalog?.messages ?? {})),
  };
}

/**
 * Builds the digest-addressed contract both bindings embed.
 *
 * `definitionsDigest` addresses the supported-definition inventory by content,
 * so a single scalar comparison detects any definition divergence even when the
 * inventories are not available side by side.
 */
export function buildBindingContract(catalog, schema) {
  const digest = buildDigestRecord(catalog, schema);

  return {
    bindingContractVersion: BINDING_CONTRACT_VERSION,
    schemaVersion: digest.schemaVersion,
    catalogVersion: digest.catalogVersion,
    locale: digest.locale,
    digestAlgorithm: digest.algorithm,
    canonicalization: digest.canonicalization,
    catalogFile: CATALOG_RELATIVE_PATH,
    catalogDigest: digest.catalogDigest,
    schemaFile: SCHEMA_RELATIVE_PATH,
    schemaDigest: digest.schemaDigest,
    digestValueFile: DIGEST_RELATIVE_PATH,
    definitionsDigest: digestJson(buildSupportedDefinitions(catalog)),
  };
}

/** Builds the full manifest embedded in both bindings. */
export function buildBindingManifest(catalog, schema) {
  return {
    contract: buildBindingContract(catalog, schema),
    supportedDefinitions: buildSupportedDefinitions(catalog),
  };
}

/**
 * Escapes text for a double-quoted JavaScript or Python string literal.
 *
 * The result is restricted to printable ASCII so the generated sources carry no
 * encoding assumptions, and every escape it emits (`\\`, `\"`, `\\uXXXX`) is
 * valid and identical in both languages as well as in JSON. That last property
 * is what lets the parity checker decode the literal with `JSON.parse`.
 */
export function escapeForStringLiteral(text) {
  let escaped = '';
  for (const character of text) {
    const codePoint = character.codePointAt(0);
    if (character === '\\') escaped += '\\\\';
    else if (character === '"') escaped += '\\"';
    else if (codePoint >= 0x20 && codePoint <= 0x7e) escaped += character;
    else {
      for (let index = 0; index < character.length; index += 1) {
        escaped += `\\u${character.charCodeAt(index).toString(16).padStart(4, '0')}`;
      }
    }
  }
  return escaped;
}

/**
 * Splits text into fixed-size code-point chunks.
 *
 * Chunking happens before escaping so no chunk can end inside an escape
 * sequence, and the fixed size keeps the split deterministic.
 */
function chunkText(text, size = LITERAL_CHUNK_SIZE) {
  const codePoints = Array.from(text);
  const chunks = [];
  for (let index = 0; index < codePoints.length; index += size) {
    chunks.push(codePoints.slice(index, index + size).join(''));
  }
  return chunks.length > 0 ? chunks : [''];
}

/** Renders a marked JavaScript literal block holding one JSON document. */
function javascriptLiteralBlock(blockName, name, jsonText) {
  const lines = chunkText(jsonText).map(
    (chunk, index, all) => `  "${escapeForStringLiteral(chunk)}"${index === all.length - 1 ? ';' : ' +'}`,
  );
  return [`// ${blockName}:begin`, `const ${name} =`, ...lines, `// ${blockName}:end`].join('\n');
}

/** Renders a marked Python literal block holding one JSON document. */
function pythonLiteralBlock(blockName, name, jsonText) {
  const lines = chunkText(jsonText).map((chunk) => `    "${escapeForStringLiteral(chunk)}"`);
  return [`# ${blockName}:begin`, `${name} = (`, ...lines, ')', `# ${blockName}:end`].join('\n');
}

/** Generated-file provenance lines shared by both languages. */
function provenanceLines(contract) {
  return [
    `Source:     ${contract.catalogFile} (catalog ${contract.catalogVersion}, schema major ${contract.schemaVersion})`,
    `Schema:     ${contract.schemaFile}`,
    `Digest:     ${contract.digestAlgorithm}:${contract.catalogDigest}`,
    'Regenerate: npm run catalog:generate',
    'Verify:     npm run catalog:bindings:check',
  ];
}

/** Builds the frontend binding source. */
export function buildJavaScriptBinding(catalog, schema) {
  const manifest = buildBindingManifest(catalog, schema);
  const contract = manifest.contract;

  return `${[
    '/**',
    ' * GENERATED FILE - DO NOT EDIT.',
    ' *',
    ' * Read-only frontend binding for the canonical chemistry catalog.',
    ' *',
    ...provenanceLines(contract).map((line) => ` * ${line}`),
    ' *',
    ' * Every exported value is deeply frozen, so shared chemistry data cannot be',
    ' * mutated by any consumer. The embedded catalog version, digests, and',
    ` * supported definitions are identical to those in ${PYTHON_BINDING_RELATIVE_PATH};`,
    ' * "npm run catalog:bindings:check" fails when they diverge.',
    ' */',
    '',
    '/** Recursively freezes parsed JSON data in place and returns it. */',
    'function deepFreeze(value) {',
    '  if (Array.isArray(value)) {',
    '    for (const item of value) deepFreeze(item);',
    '    return Object.freeze(value);',
    '  }',
    '  if (value !== null && typeof value === "object") {',
    '    for (const key of Object.keys(value)) deepFreeze(value[key]);',
    '    return Object.freeze(value);',
    '  }',
    '  return value;',
    '}',
    '',
    javascriptLiteralBlock(MANIFEST_BLOCK, 'MANIFEST_JSON', canonicalizeJson(manifest)),
    '',
    javascriptLiteralBlock(CATALOG_BLOCK, 'CATALOG_JSON', canonicalizeJson(catalog)),
    '',
    'const MANIFEST = deepFreeze(JSON.parse(MANIFEST_JSON));',
    '',
    '/** Deeply frozen canonical chemistry catalog. */',
    'export const CATALOG = deepFreeze(JSON.parse(CATALOG_JSON));',
    '',
    '/** Digest-addressed identity of this catalog release, shared with the backend binding. */',
    'export const BINDING_CONTRACT = MANIFEST.contract;',
    '',
    '/** Definition inventory this binding supports, shared with the backend binding. */',
    'export const SUPPORTED_DEFINITIONS = MANIFEST.supportedDefinitions;',
    '',
    'export const BINDING_CONTRACT_VERSION = BINDING_CONTRACT.bindingContractVersion;',
    'export const SCHEMA_VERSION = BINDING_CONTRACT.schemaVersion;',
    'export const CATALOG_VERSION = BINDING_CONTRACT.catalogVersion;',
    'export const LOCALE = BINDING_CONTRACT.locale;',
    'export const DIGEST_ALGORITHM = BINDING_CONTRACT.digestAlgorithm;',
    'export const CANONICALIZATION = BINDING_CONTRACT.canonicalization;',
    'export const CATALOG_DIGEST = BINDING_CONTRACT.catalogDigest;',
    'export const SCHEMA_DIGEST = BINDING_CONTRACT.schemaDigest;',
    'export const DEFINITIONS_DIGEST = BINDING_CONTRACT.definitionsDigest;',
  ].join('\n')}\n`;
}

/** Builds the backend binding source. */
export function buildPythonBinding(catalog, schema) {
  const manifest = buildBindingManifest(catalog, schema);
  const contract = manifest.contract;

  return `${[
    '"""GENERATED FILE - DO NOT EDIT.',
    '',
    'Read-only backend binding for the canonical chemistry catalog.',
    '',
    ...provenanceLines(contract),
    '',
    'Mappings are exposed as ``MappingProxyType`` and sequences as tuples, so the',
    'shared chemistry data is deeply read-only. The embedded catalog version,',
    `digests, and supported definitions are identical to those in`,
    `${JAVASCRIPT_BINDING_RELATIVE_PATH}; "npm run catalog:bindings:check" fails`,
    'when they diverge.',
    '"""',
    '',
    'from __future__ import annotations',
    '',
    'import json',
    'from types import MappingProxyType',
    'from typing import Any',
    '',
    '__all__ = [',
    '    "BINDING_CONTRACT",',
    '    "BINDING_CONTRACT_VERSION",',
    '    "CANONICALIZATION",',
    '    "CATALOG",',
    '    "CATALOG_DIGEST",',
    '    "CATALOG_VERSION",',
    '    "DEFINITIONS_DIGEST",',
    '    "DIGEST_ALGORITHM",',
    '    "LOCALE",',
    '    "SCHEMA_DIGEST",',
    '    "SCHEMA_VERSION",',
    '    "SUPPORTED_DEFINITIONS",',
    ']',
    '',
    '',
    'def _freeze(value: Any) -> Any:',
    '    """Returns a deeply read-only view of parsed JSON data."""',
    '    if isinstance(value, dict):',
    '        return MappingProxyType({key: _freeze(item) for key, item in value.items()})',
    '    if isinstance(value, list):',
    '        return tuple(_freeze(item) for item in value)',
    '    return value',
    '',
    '',
    pythonLiteralBlock(MANIFEST_BLOCK, '_MANIFEST_JSON', canonicalizeJson(manifest)),
    '',
    pythonLiteralBlock(CATALOG_BLOCK, '_CATALOG_JSON', canonicalizeJson(catalog)),
    '',
    '_MANIFEST = _freeze(json.loads(_MANIFEST_JSON))',
    '',
    '#: Deeply read-only canonical chemistry catalog.',
    'CATALOG = _freeze(json.loads(_CATALOG_JSON))',
    '',
    '#: Digest-addressed identity of this catalog release, shared with the frontend binding.',
    'BINDING_CONTRACT = _MANIFEST["contract"]',
    '',
    '#: Definition inventory this binding supports, shared with the frontend binding.',
    'SUPPORTED_DEFINITIONS = _MANIFEST["supportedDefinitions"]',
    '',
    'BINDING_CONTRACT_VERSION = BINDING_CONTRACT["bindingContractVersion"]',
    'SCHEMA_VERSION = BINDING_CONTRACT["schemaVersion"]',
    'CATALOG_VERSION = BINDING_CONTRACT["catalogVersion"]',
    'LOCALE = BINDING_CONTRACT["locale"]',
    'DIGEST_ALGORITHM = BINDING_CONTRACT["digestAlgorithm"]',
    'CANONICALIZATION = BINDING_CONTRACT["canonicalization"]',
    'CATALOG_DIGEST = BINDING_CONTRACT["catalogDigest"]',
    'SCHEMA_DIGEST = BINDING_CONTRACT["schemaDigest"]',
    'DEFINITIONS_DIGEST = BINDING_CONTRACT["definitionsDigest"]',
  ].join('\n')}\n`;
}

/** The two generated bindings, keyed by the identifier the reports use. */
export const BINDING_TARGETS = Object.freeze([
  Object.freeze({
    id: 'javascript',
    language: 'JavaScript',
    relativePath: JAVASCRIPT_BINDING_RELATIVE_PATH,
    build: buildJavaScriptBinding,
  }),
  Object.freeze({
    id: 'python',
    language: 'Python',
    relativePath: PYTHON_BINDING_RELATIVE_PATH,
    build: buildPythonBinding,
  }),
]);

/**
 * Decodes one marked literal block from a generated binding source.
 *
 * The block is read textually rather than by importing or executing the
 * binding, so the parity checker needs no JavaScript module loader, no Python
 * interpreter, and no trust in the file it is inspecting.
 */
export function extractEmbeddedJson(source, blockName) {
  if (typeof source !== 'string') {
    return { value: null, reason: 'the binding source is unavailable' };
  }

  const begin = source.indexOf(`${blockName}:begin`);
  const end = source.indexOf(`${blockName}:end`);
  if (begin < 0 || end < 0 || end < begin) {
    return { value: null, reason: `the ${blockName} block markers are missing` };
  }

  const segments = [...source.slice(begin, end).matchAll(/"((?:[^"\\]|\\.)*)"/gu)].map((match) => match[1]);
  if (segments.length === 0) {
    return { value: null, reason: `the ${blockName} block contains no string literal` };
  }

  let jsonText;
  try {
    jsonText = JSON.parse(`"${segments.join('')}"`);
  } catch {
    return { value: null, reason: `the ${blockName} literal is not decodable` };
  }

  try {
    return { value: JSON.parse(jsonText), reason: null };
  } catch {
    return { value: null, reason: `the ${blockName} literal does not contain valid JSON` };
  }
}

/** Decodes the embedded manifest of a generated binding source. */
export function extractBindingManifest(source) {
  const extracted = extractEmbeddedJson(source, MANIFEST_BLOCK);
  if (!extracted.value) return extracted;
  const manifest = extracted.value;
  if (!manifest.contract || !manifest.supportedDefinitions) {
    return { value: null, reason: 'the embedded manifest is missing its contract or supported definitions' };
  }
  return { value: manifest, reason: null };
}
