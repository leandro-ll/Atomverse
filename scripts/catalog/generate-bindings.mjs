/**
 * Deterministic generation of the read-only chemistry catalog bindings.
 *
 * Writing `js/generated/chemistry-catalog.js` and
 * `backend/app/generated/chemistry_catalog.py` is a pure function of the
 * committed catalog and schema, so regenerating from unchanged artifacts
 * rewrites the same bytes. Generation refuses to run on a catalog that does not
 * pass validation: a binding is the artifact every calculation reads, so it must
 * never carry an unvalidated or digest-drifted catalog into either runtime.
 *
 * Usage:
 *   node scripts/catalog/generate-bindings.mjs            # write both bindings
 *   node scripts/catalog/generate-bindings.mjs --check    # verify without writing
 *   node scripts/catalog/generate-bindings.mjs --skip-validation
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { BINDING_TARGETS } from './catalog-bindings.mjs';
import {
  CATALOG_PATH,
  JAVASCRIPT_BINDING_PATH,
  PYTHON_BINDING_PATH,
  SCHEMA_PATH,
  readJsonArtifact,
  readTextArtifact,
} from './catalog-paths.mjs';
import { validateCommittedCatalog } from './validate-catalog.mjs';

/** Resolves the output path of each binding, allowing tests to redirect them. */
export function resolveBindingPaths({ javascriptPath = JAVASCRIPT_BINDING_PATH, pythonPath = PYTHON_BINDING_PATH } = {}) {
  return { javascript: javascriptPath, python: pythonPath };
}

/**
 * Generates both bindings.
 *
 * With `check` set, nothing is written and every binding whose committed bytes
 * differ from the regenerated bytes is reported as stale.
 */
export async function generateBindings({ check = false, validate = true, ...pathOverrides } = {}) {
  const paths = resolveBindingPaths(pathOverrides);

  if (validate) {
    const validation = await validateCommittedCatalog();
    if (!validation.ok) {
      return {
        ok: false,
        bindings: [],
        reason:
          `the committed catalog failed validation with ${validation.violations.length} violation(s). ` +
          'Fix the catalog before generating bindings.',
        validation,
      };
    }
  }

  const [catalog, schema] = await Promise.all([readJsonArtifact(CATALOG_PATH), readJsonArtifact(SCHEMA_PATH)]);
  if (!catalog || !schema) {
    return {
      ok: false,
      bindings: [],
      reason: 'the committed catalog and schema artifacts must both exist',
      validation: null,
    };
  }

  const bindings = [];
  for (const target of BINDING_TARGETS) {
    const path = paths[target.id];
    const expected = target.build(catalog, schema);
    const committed = await readTextArtifact(path);
    const current = committed === expected;

    if (current || check) {
      bindings.push({
        id: target.id,
        relativePath: target.relativePath,
        path,
        written: false,
        current,
        bytes: expected.length,
      });
      continue;
    }

    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, expected, 'utf8');
    bindings.push({
      id: target.id,
      relativePath: target.relativePath,
      path,
      written: true,
      current: false,
      bytes: expected.length,
    });
  }

  const stale = bindings.filter((binding) => !binding.current && !binding.written);
  if (stale.length > 0) {
    return {
      ok: false,
      bindings,
      reason:
        `${stale.map((binding) => binding.relativePath).join(', ')} ` +
        'is out of date. Regenerate with "npm run catalog:generate".',
      validation: null,
    };
  }

  const written = bindings.filter((binding) => binding.written);
  return {
    ok: true,
    bindings,
    reason:
      written.length > 0
        ? `generated ${written.map((binding) => binding.relativePath).join(', ')}`
        : 'both bindings are already current',
    validation: null,
  };
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  const result = await generateBindings({
    check: process.argv.includes('--check'),
    validate: !process.argv.includes('--skip-validation'),
  });

  process.stdout.write(`${result.ok ? '[catalog]' : '[catalog] error:'} ${result.reason}\n`);
  for (const binding of result.bindings) {
    const state = binding.written ? 'written' : binding.current ? 'current' : 'stale';
    process.stdout.write(`[catalog] ${binding.relativePath} ${state} (${binding.bytes} bytes)\n`);
  }
  for (const violation of result.validation?.violations ?? []) {
    process.stdout.write(`[catalog]   - ${violation.code} at ${violation.path}: ${violation.message}\n`);
  }
  if (!result.ok) process.exitCode = 1;
}
