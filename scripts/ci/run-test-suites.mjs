/**
 * CI test-suite runner.
 *
 * Resolves every registered suite, applies the declared empty-suite policy, and
 * invokes only the suites that actually matched test files. Use `--dry-run` to
 * print the resolution plan without executing any suite.
 */

import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  interpretExitCode,
  listRepositoryFiles,
  loadRegistry,
  matchSuiteFiles,
  resolveCommand,
  resolveSuiteStatus,
  validateRegistry,
} from './test-suite-registry.mjs';

export async function planSuites(rootDirectory, registry) {
  const repositoryFiles = await listRepositoryFiles(rootDirectory);
  return registry.suites.map((suite) => {
    const matchedFiles = matchSuiteFiles(suite, repositoryFiles);
    const { status, reason } = resolveSuiteStatus(suite, matchedFiles.length);
    return { suite, matchedFiles, status, reason };
  });
}

function runSuite(suite, rootDirectory) {
  const { executable, args } = resolveCommand(suite, { rootDirectory });
  const cwd = resolve(rootDirectory, suite.cwd ?? '.');
  process.stdout.write(`\n[ci] ${suite.id}: ${executable} ${args.join(' ')} (cwd: ${suite.cwd ?? '.'})\n`);

  // Suites must not leave generated bytecode behind: the release policy denies it.
  const environment = { ...process.env, PYTHONDONTWRITEBYTECODE: '1' };

  return new Promise((resolvePromise, rejectPromise) => {
    const child = spawn(executable, args, { cwd, env: environment, stdio: 'inherit', shell: false });
    child.on('error', rejectPromise);
    child.on('close', (code) => resolvePromise(code ?? 1));
  });
}

export async function runRegisteredSuites(rootDirectory, { dryRun = false } = {}) {
  const registry = await loadRegistry();
  const registryViolations = validateRegistry(registry).map((reason) => ({ suiteId: 'registry', type: 'invalid-registry', reason }));
  const plan = await planSuites(rootDirectory, registry);
  const results = [];
  const violations = [...registryViolations];

  for (const entry of plan) {
    const { suite, status, reason, matchedFiles } = entry;
    if (status === 'violation') {
      violations.push({ suiteId: suite.id, type: 'empty-suite', reason });
      results.push({ suiteId: suite.id, status, outcome: 'violation', matchedFiles: matchedFiles.length, reason });
      continue;
    }
    if (status === 'declared-empty') {
      process.stdout.write(`[ci] ${suite.id}: declared-empty (${reason})\n`);
      results.push({ suiteId: suite.id, status, outcome: 'skipped', matchedFiles: 0, reason });
      continue;
    }
    if (dryRun) {
      results.push({ suiteId: suite.id, status, outcome: 'not-run', matchedFiles: matchedFiles.length, reason });
      continue;
    }

    const { executable } = resolveCommand(suite, { rootDirectory });
    if (executable.includes('python') && !existsSync(executable)) {
      violations.push({
        suiteId: suite.id,
        type: 'missing-interpreter',
        reason: `Python interpreter ${executable} not found. Create the backend environment or set ATOMVERSE_PYTHON.`,
      });
      results.push({ suiteId: suite.id, status, outcome: 'violation', matchedFiles: matchedFiles.length, reason });
      continue;
    }

    const exitCode = await runSuite(suite, rootDirectory);
    const { outcome, reason: outcomeReason } = interpretExitCode(registry, suite.runner, exitCode);
    results.push({ suiteId: suite.id, status, outcome, matchedFiles: matchedFiles.length, exitCode, reason: outcomeReason });
    if (outcome !== 'passed') {
      violations.push({ suiteId: suite.id, type: `suite-${outcome}`, reason: outcomeReason });
    }
  }

  return { registryVersion: registry.registryVersion, dryRun, results, violations };
}

const invokedPath = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedPath) {
  const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const report = await runRegisteredSuites(rootDirectory, { dryRun: process.argv.includes('--dry-run') });
  process.stdout.write(`\n${JSON.stringify(report, null, 2)}\n`);
  if (report.violations.length > 0) {
    process.stderr.write(`CI test-suite run failed with ${report.violations.length} violation(s).\n`);
    process.exitCode = 1;
  }
}
