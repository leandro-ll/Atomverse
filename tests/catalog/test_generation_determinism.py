"""Property test 3: Generation is byte-stable and digest-stable.

Validates: Requirements 2.4, 2.5, 12.5
For any process hash seed and any two executions over an unchanged seed and
unchanged generator, the emitted catalog bytes are identical and the computed
digest is identical.
"""

from pathlib import Path
import pytest
from scripts.catalog.validate_seed import validate_seed
from scripts.catalog.generate import enumerate_substances, enumerate_reactions
from scripts.catalog.emit import build_catalog_bundle, canonical_dumps

ROOT = Path(__file__).resolve().parents[2]
SEED_DIR = ROOT / "catalog" / "seed"


def test_generation_determinism_property():
    seed1 = validate_seed(SEED_DIR)
    substances1 = enumerate_substances(seed1)
    reactions1 = enumerate_reactions(substances1, seed1)
    cat1, dig1, cov1 = build_catalog_bundle(substances1, reactions1, seed1, ROOT)
    bytes1 = canonical_dumps(cat1).encode("utf-8")

    seed2 = validate_seed(SEED_DIR)
    substances2 = enumerate_substances(seed2)
    reactions2 = enumerate_reactions(substances2, seed2)
    cat2, dig2, cov2 = build_catalog_bundle(substances2, reactions2, seed2, ROOT)
    bytes2 = canonical_dumps(cat2).encode("utf-8")

    # Byte equality across runs
    assert bytes1 == bytes2, "Repeated generation produced differing bytes"
    assert dig1["digest"] == dig2["digest"], "Repeated generation produced differing digests"
    assert dig1["bytes"] == dig2["bytes"] == len(bytes1)

    # Equality against committed catalog file
    committed_path = ROOT / "catalog" / "chemistry.catalog.json"
    assert committed_path.exists(), "Committed catalog file missing"
    committed_bytes = committed_path.read_bytes()
    assert committed_bytes == bytes1, "Committed catalog bytes do not match freshly generated bytes"
